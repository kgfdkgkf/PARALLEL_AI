def answer(body: dict) -> str:
    messages = body.get("messages") or []
    system = " ".join(str(item.get("content", "")) for item in messages if item.get("role") == "system").lower()
    if "проверяешь соединение" in system:
        return json.dumps({"ok": True}, ensure_ascii=False)
    if "архитектор альтернативных вселенных" in system:
        return json.dumps(WORLD, ensure_ascii=False)
    if "сценарист" in system:
        return json.dumps(DECISION, ensure_ascii=False)
    if "житель" in system or "реплика" in system:
        return json.dumps({"text": "Я инспектор акустики, и я отвечаю за тишину в этом городе. Ты спрашиваешь про счётчики — значит, платишь или собираешься. В любом случае приходи после четырнадцати: в тихий час говорить дешевле."}, ensure_ascii=False)
    return json.dumps({"ok": True}, ensure_ascii=False)


class Handler(BaseHTTPRequestHandler):
    def log_message(self, format: str, *args) -> None:  # noqa: A002
        print("MOCK-LLM", format % args)

    def _send(self, payload: dict, status: int = 200) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Headers", "*")
        self.send_header("Access-Control-Allow-Methods", "POST, OPTIONS")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_OPTIONS(self) -> None:  # noqa: N802
        self._send({}, 204)

    def do_POST(self) -> None:  # noqa: N802
        length = int(self.headers.get("Content-Length", "0"))
        raw = self.rfile.read(length) if length else b"{}"
        try:
            body = json.loads(raw.decode("utf-8"))
        except json.JSONDecodeError:
            body = {}
        content = answer(body)
        self._send({"id": "mock", "choices": [{"index": 0, "message": {"role": "assistant", "content": content}}]})


