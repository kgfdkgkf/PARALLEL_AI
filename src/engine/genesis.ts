function pick<T>(random: () => number, items: T[]): T {
  return items[Math.floor(random() * items.length) % items.length];
}

function take<T>(random: () => number, items: T[], count: number): T[] {
  const pool = [...items];
  const result: T[] = [];
  while (pool.length > 0 && result.length < count) {
    result.push(pool.splice(Math.floor(random() * pool.length), 1)[0]);
  }
  return result;
}

export function buildGenesisPack(question: string): ThemePack {
  const core = hypothesisText(question) || 'правило изменилось';
  const topic = core.length <= 46 ? core : core.slice(0, 46).replace(/\s+\S*$/, '') + '…';
  const scenario = scenarioFor(core);
  const rule = core.charAt(0).toUpperCase() + core.slice(1) + '.';
  const random = mulberry32(hashString(`${question}:genesis`));

  const laws = [
    rule,
    `Районные службы публикуют, как они приспособились: ${scenario.adaptation}.`,
    'Школы один раз в год проводят учения по местному аварийному плану.',
    'Жители вправе запросить исходные наблюдения, на которых основано решение районной службы.',
    'Общие меры пересматривают после совместного испытания хотя бы в двух районах.',
  ];

  const places: LocationSeed[] = [{
    name: scenario.district,
    kind: 'Квартал',
    blurb: `Здесь первым заметили, к чему приводит новое условие: ${core}.`,
    detail: `Именно здесь ${scenario.adaptation}. Теперь местные обсуждают, как быть дальше: ${scenario.failure}.`,
  }, ...take(random, PLACE_GENERIC, 1)];
  const usedKinds = new Set(places.map((place) => place.kind));
  const namedKinds = PLACE_KINDS.filter((kind) => !usedKinds.has(kind)).slice(0, 3);
  namedKinds.forEach((kind) => {
    const map: Record<string, { blurb: string; detail: string }> = {
      Институт: {
        blurb: `Главный орган, который следит за правилом «${topic}».`,
        detail: 'В коридорах висят схемы, а не портреты. Сотрудники говорят шёпотом — так принято с самого начала.',
      },
      Бюро: {
        blurb: 'Здесь выдают разрешения и отказы.',
        detail: 'Очередь двигается медленно, потому что каждое дело проверяют дважды. Отказ стоит дороже разрешения и оформляется быстрее.',
      },
      Площадь: {
        blurb: `Место, где объявили правило «${topic}».`,
        detail: 'Постамент остался пустым: официальная версия событий менялась четыре раза, и табличку перестали обновлять.',
      },
      Квартал: {
        blurb: 'Район, где живут те, кто помнит, как было раньше.',
        detail: 'Здесь хранят вещи прежнего мира и учат внуков слову «раньше» — тихо, чтобы не услышали соседи.',
      },
      Музей: {
        blurb: 'Экспозиция о том, как правило стало обыденностью.',
        detail: 'Экскурсии ведут по расписанию, а последний зал закрыт: там хранят предметы, которые правило запрещает показывать.',
      },
      Станция: {
        blurb: 'Точка, откуда наблюдают за последствиями.',
        detail: 'Приборы фиксируют не нарушения, а настроение: сколько людей за неделю назвали правило «нормальным».',
      },
    };
    const seed = map[kind];
    places.push({
      name: `${kind} городских испытаний`,
      kind,
      blurb: seed.blurb,
      detail: seed.detail,
    });
  });

  const culture = dedupeCulture([
    {
      label: 'Ритуал',
      value: `Каждый год в семьях пересказывают, как появилось правило «${topic}». Каждый раз история звучит иначе — и это считается нормальным.`,
    },
    ...take(random, CULTURE_POOL, 4),
  ]);

  const castSeeds = take(random, NAMES, 3);
  const cast: CastSeed[] = castSeeds.map((seed, index) => {
    const bio = pick(random, BIO_TEMPLATE)(topic);
    return {
      name: seed.name,
      role: index === 0 ? scenario.trade : pick(random, ROLE_POOL),
      age: 24 + Math.floor(random() * 38),
      bio,
      goal: pick(random, GOAL_POOL),
      fear: pick(random, FEAR_POOL),
      secret: pick(random, SECRET_POOL),
      quote: pick(random, QUOTE_POOL),
      stance: seed.stance,
      sigil: ['◈', '◇', '⌘'][index % 3],
    };
  });

  const baseYear = 2040 + Math.floor(random() * 30);
  const eras = [
    {
      year: baseYear,
      title: 'Сдвиг',
      text: `Появляются первые свидетельства того, что мир изменился: ${core}. Несколько районов проводят независимые проверки.`,
    },
    {
      year: baseYear + 16,
      title: 'Адаптация',
      text: `Первые меры становятся привычными: ${scenario.adaptation}.`,
    },
    {
      year: baseYear + 34,
      title: 'Кодификация',
      text: 'Правило записывают в закон. Возникает институт, который его охраняет, и первая волна тех, кто не согласен.',
    },
    {
      year: baseYear + 58,
      title: 'Предел',
      text: `Общий порядок приходится пересмотреть после нового случая: ${scenario.failure}.`,
    },
  ];

  const title = `МИР, ГДЕ ${topic.toUpperCase()}`;

  return {
    ...GENESIS_TEMPLATE,
    id: 'genesis',
    title,
    codename: 'СДВИГ',
    genre: 'Спекулятивная история',
    era: baseYear + 60,
    rule,
    premise: `В ${baseYear} году изменилось одно условие: ${core}. За шестьдесят лет люди смогли приспособиться: ${scenario.adaptation}. Теперь это решение проверяет новый случай: ${scenario.failure}.`,
    laws,
    locations: places.slice(0, 5),
    culture,
    eras,
    cast,
    lexicon: GENESIS_TEMPLATE.lexicon,
  } as ThemePack;
}
